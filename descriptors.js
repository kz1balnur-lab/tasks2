/* Word кестесін екі бағанды кестеге ауыстыру (tasks-data.js жүктелгеннен кейін бірден орындалады) */
(function () {
  const D = window.PHYS_DESCRIPTORS || {};
  const plain = (bs) => (bs || []).map(b => (b.t === 'p' ? String(b.h || '').replace(/<[^>]+>/g, '').replace(/&nbsp;/g, ' ') : '')).join(' ').trim();
  const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  const cell = (h) => ({ b: [{ t: 'p', h }] });
  // «F_теңәсер» → F<sub>теңәсер</sub> (render.js subHTML-мен бірдей ереже)
  const sub = (h) => h.replace(/([A-Za-z])_([А-Яа-яӘәІіҢңҒғҮүҰұҚқӨөҺһЁё]+)/g, '$1<sub>$2</sub>');

  // Word кестесіндегі балдар (тақырып және «Барлығы» жолдарынсыз) — grading.js descriptorRows() логикасымен бірдей
  function originalPoints(tbl) {
    const rows = tbl.rows, hdr = rows[0].map(c => plain(c.b));
    let pCol = hdr.findIndex(h => /^Балл/i.test(h)); if (pCol < 0) pCol = hdr.length - 1;
    const colsOf = (rw) => { const o = []; let p = 0; rw.forEach(c => { o.push(p); p += c.cs || 1; }); return o; };
    const pPos = colsOf(rows[0])[pCol];
    const out = [];
    rows.forEach((rw, ri) => {
      if (ri === 0 || rw.some(c => /^Барлығы/i.test(plain(c.b)))) return;
      const i = colsOf(rw).indexOf(pPos);
      const pc = i >= 0 ? rw[i] : rw[rw.length - 1];
      const v = pc ? parseFloat(plain(pc.b).replace(',', '.')) : NaN;
      if (!isNaN(v)) out.push(v);
    });
    return out;
  }

  (window.PHYS_TOPICS || []).forEach(T => (T.objectives || []).forEach(o => (o.tasks || []).forEach(task => {
    const list = D[task.id];
    if (!list || !task.descriptors || !task.descriptors.rows) return;
    const orig = originalPoints(task.descriptors);
    const pts = list.map(x => x[1]);
    if (orig.length !== pts.length || orig.some((v, i) => v !== pts[i])) {
      console.warn('[descriptors] ' + task.id + ': дескриптор саны немесе балы Word кестесімен сәйкес емес (' + orig.join('+') + ' ≠ ' + pts.join('+') + ') — бастапқы кесте қалдырылды');
      return;
    }
    const total = pts.reduce((a, b) => a + b, 0);
    task.descriptors_word = task.descriptors; // Word-тағы бастапқы кесте (салыстыру үшін)
    task.descriptors = {
      t: 'tbl',
      rows: [[cell('<b>Дескриптор</b>'), cell('<b>Балл</b>')]]
        .concat(list.map(([text, p]) => [cell(sub(esc(text))), cell(String(p))]))
        .concat([[cell('<b>Барлығы</b>'), cell('<b>' + total + '</b>')]])
    };
  })));
})();
