/*
 * БЕЛГІЛЕУЛЕРДІ АУЫСТЫРУ — оқу мақсатының бүкіл тобында: «Есте сақтаңыз», шарт, шешу жолы, жауап.
 * Сабақ №29 «Бір түзу бойымен денеге әрекет еткен күштерді қосу»: тең әрекетті күш R → F<sub>теңәсер</sub>.
 * Тек жеке тұрған «R» ауыстырылады (сөз немесе басқа белгі ішіндегі R өзгермейді).
 */
window.PHYS_SYMBOL_FIXES = {
  t4o4: [[/(^|[^A-Za-z0-9_])R(?![A-Za-z0-9_])/g, '$1F<sub>теңәсер</sub>']],
  t4o5: [
    [/(^|[^A-Za-z0-9_])R(?![A-Za-z0-9_])/g, '$1F<sub>теңәсер</sub>'],
    [/Ғ<sub>теңәсер<\/sub>/g, 'F<sub>теңәсер</sub>']   // «Есте сақтаңыз»: қазақтың «Ғ» әрпі емес, латынның F-і
  ]
};

(function () {
  const F = window.PHYS_TEXT_FIXES || {};
  const count = (s, sub) => s.split(sub).length - 1;
  // шарттағы барлық абзацтар (кестелер мен қоршаулардың ішіндегілерін қоса)
  function paragraphs(bs, out) {
    (bs || []).forEach(b => {
      if (b.t === 'p') out.push(b);
      if (b.b) paragraphs(b.b, out);
      if (b.rows) b.rows.forEach(r => r.forEach(c => paragraphs(c.b, out)));
    });
    return out;
  }
  (window.PHYS_TOPICS || []).forEach(T => (T.objectives || []).forEach(o => (o.tasks || []).forEach(task => {
    (F[task.id] || []).forEach(([from, to]) => {
      const ps = paragraphs(task.condition, []).filter(p => String(p.h).indexOf(from) >= 0);
      if (ps.length !== 1 || count(ps[0].h, from) !== 1) {
        console.warn('[task-text-fixes] ' + task.id + ': «' + from + '» мәтіні ' + (ps.length ? 'бірнеше рет' : 'табылмады') + ' — өзгертілмеді');
        return;
      }
      ps[0].h = ps[0].h.replace(from, to);
    });
  })));

  // белгілеулер: топтағы барлық «h» (абзац) және «answer» мәтіндері
  const S = window.PHYS_SYMBOL_FIXES || {};
  const KEYS = { h: 1, answer: 1 };
  function walk(x, rules) {
    if (Array.isArray(x)) { x.forEach(v => walk(v, rules)); return; }
    if (!x || typeof x !== 'object') return;
    Object.keys(x).forEach(k => {
      if (typeof x[k] === 'string') { if (KEYS[k]) rules.forEach(([re, to]) => { x[k] = x[k].replace(re, to); }); }
      else walk(x[k], rules);
    });
  }
  (window.PHYS_TOPICS || []).forEach(T => (T.objectives || []).forEach(o => { if (S[o.id]) walk(o, S[o.id]); }));
})();
